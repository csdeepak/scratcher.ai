// INDEX.md: a generated, read-only overview of one roadmap so an agent can understand the
// whole structure (ids, status, files, problems, pending review) without opening every file.

import type { Roadmap } from '../shared/model';
import { getProfile, statusDef } from '../shared/profiles';
import { childrenIndex, computeProgress } from '../shared/tree';
import { fieldLabel } from '../shared/fields';
import { HOLD_REASON_TEXT } from '../shared/guard';
import type { ReviewItem } from './review';

export function renderIndex(rm: Roadmap, held: ReviewItem[], proposals: string[]): string {
  const profile = getProfile(rm.meta.profile);
  const progress = computeProgress(rm.checkpoints, rm.meta);
  const total = progress.get(null)!;
  const idx = childrenIndex(rm.checkpoints);
  const drafts = Object.values(rm.checkpoints).filter((c) => !c.approved && !c.archived).length;
  const lines: string[] = [];
  lines.push('<!-- Generated by Waymark. Do not edit: this file is rewritten on every change. Edit the checkpoint files instead. -->');
  lines.push(`# ${rm.meta.title}`);
  lines.push('');
  if (rm.meta.description) lines.push(rm.meta.description, '');
  lines.push(`- Roadmap id: \`${rm.meta.id}\` · profile: **${profile.key}** · default agent access: **${rm.meta.agentAccess}**`);
  lines.push(
    `- Progress: ${total.done} of ${total.total} complete${profile.understanding ? ` · ${total.understood} understood` : ''} · ${drafts} draft (not yet approved)`,
  );
  lines.push(`- Statuses in this profile: ${profile.statuses.map((s) => `\`${s.key}\``).join(', ')}`);
  lines.push(`- Sections: ${profile.sections.map((k) => `\`${k}\``).join(', ')}`);
  lines.push('');

  const attention: string[] = [];
  for (const p of rm.problems) attention.push(`- ⚠ **${p.file}**: ${p.message}`);
  for (const h of held) {
    if (h.kind === 'held-delete') attention.push(`- ⏸ Deleting "${h.title}" is waiting for the human's approval. The file was put back; do not delete it again.`);
    else {
      const what = h.changes.map((c) => `${fieldLabel(c.field)} (${c.reason ? HOLD_REASON_TEXT[c.reason] : 'held'})`).join(', ');
      attention.push(`- ⏸ Held for review in "${h.title}": ${what}. Those edits were NOT applied; the file shows the current values.`);
    }
  }
  for (const p of proposals) attention.push(`- 📝 Proposal waiting for review: proposals/${p}`);
  if (attention.length) {
    lines.push('## Needs attention', '', ...attention, '');
  }

  lines.push('## Outline', '');
  lines.push('Format: `[status]` title `id` — file · flags', '');
  const walk = (parent: string, depth: number) => {
    for (const cp of idx.get(parent) ?? []) {
      if (cp.archived) continue;
      const flags: string[] = [];
      flags.push(cp.approved ? 'approved' : 'draft');
      if (cp.optional) flags.push('optional');
      if (cp.agentAccess) flags.push(`agentAccess: ${cp.agentAccess}`);
      if (profile.understanding && cp.understanding && cp.understanding !== 'not-yet') flags.push(cp.understanding);
      if (cp.prerequisites.length) flags.push(`requires ${cp.prerequisites.map((p) => `\`${p}\``).join(' ')}`);
      const p = progress.get(cp.id);
      if (p && p.total) flags.push(`${p.done}/${p.total} sub done`);
      const status = statusDef(profile, cp.status);
      lines.push(`${'  '.repeat(depth)}- \`[${status.key}]\` ${depth === 0 ? `**${cp.title}**` : cp.title} \`${cp.id}\` — ${rm.files[cp.id] ?? '?'} · ${flags.join(' · ')}`);
      walk(cp.id, depth + 1);
    }
  };
  walk('', 0);
  if (!(idx.get('') ?? []).length) lines.push('_No checkpoints yet._');
  const archived = Object.values(rm.checkpoints).filter((c) => c.archived);
  if (archived.length) {
    lines.push('', '## Archived', '');
    for (const cp of archived) lines.push(`- ${cp.title} \`${cp.id}\` — ${rm.files[cp.id] ?? '?'}`);
  }
  lines.push('');
  return lines.join('\n');
}
